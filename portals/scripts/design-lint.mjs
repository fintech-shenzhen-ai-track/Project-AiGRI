#!/usr/bin/env node
// Design lint: the static half of the rules in AGENTS.md section 5 ("Frontend").
// The "at most one btn-y per route or dialog" rule is checked in Playwright (T-03.20).
//
// Usage: node scripts/design-lint.mjs [dir-or-file ...]   (default: the portals source folders)
import { readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_TARGETS = ["app", "components", "lib", "styles", "public"];
const SKIP_DIRS = new Set(["node_modules", ".next", "tests", "e2e", "scripts", "test-results", "playwright-report"]);
const SKIP_FILES = new Set(["types.ts"]); // generated by openapi-typescript
const CODE_EXT = new Set([".ts", ".tsx", ".js", ".jsx", ".mjs"]);
const CSS_EXT = new Set([".css"]);

/** Banned everywhere in portal source (code, CSS, copy). */
const BANNED_PHRASES = ["AiGRI approved", "auto-approved", "AI decided"];

/** Literals that must come from the country pack, never from component code. */
const PACK_LITERALS = [
  { re: /\bRp\b/, name: "Rp" },
  { re: /\bPHP\b/, name: "PHP" },
  { re: /\bIDR\b/, name: "IDR" },
  { re: / ha\b/, name: " ha" },
  { re: /\bWIB\b/, name: "WIB" },
  { re: /\bOJK\b/, name: "OJK" },
  { re: /\bBI-FAST\b/, name: "BI-FAST" },
];

/** Style rules, checked against CSS declarations (CSS files and style strings alike). */
const STYLE_RULES = [
  { re: /\d(?:vh|vw|svh|dvh|lvh)\b/, msg: "viewport units (vh, vw, svh, dvh, lvh) are banned" },
  { re: /\bdashed\b/, msg: "dashed is banned" },
  { re: /backdrop-filter/, msg: "backdrop-filter is banned" },
  { re: /(?<![-\w])ease-in(?![-\w])/, msg: "ease-in alone is banned (use ease-out or ease-in-out)" },
  { re: /scale\(\s*0\s*\)/, msg: "scale(0) is banned" },
  { re: /transition\s*:\s*all\b/, msg: "transition: all is banned" },
];

// border: or border-* declarations, except border:0 and the shape-only properties.
const BORDER_DECL = /(?<![-\w])(border(?:-[a-z]+)*)\s*:\s*([^;}"'`]*)/g;
const BORDER_OK_PROPS = /^border(?:-(?:[a-z]+-)?radius|-collapse|-spacing)$/;
const OUTLINE_DECL = /(?<![-\w])outline(?:-[a-z]+)*\s*:/;

function walk(target, out) {
  const st = statSync(target, { throwIfNoEntry: false });
  if (!st) return;
  if (st.isFile()) {
    out.push(target);
    return;
  }
  for (const name of readdirSync(target)) {
    const full = path.join(target, name);
    const s = statSync(full);
    if (s.isDirectory()) {
      if (!SKIP_DIRS.has(name)) walk(full, out);
    } else if (!SKIP_FILES.has(name)) {
      out.push(full);
    }
  }
}

function stripComments(src, ext) {
  let out = src.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "));
  if (CODE_EXT.has(ext)) out = out.replace(/(^|[\s;,{(])\/\/.*$/gm, (m, p1) => p1);
  return out;
}

function lineOf(src, index) {
  return src.slice(0, index).split("\n").length;
}

function checkBorder(src, file, violations) {
  for (const m of src.matchAll(BORDER_DECL)) {
    const [, prop, rawValue = ""] = m;
    if (!prop || BORDER_OK_PROPS.test(prop)) continue;
    if (prop === "border" && /^0(?:px)?$/.test(rawValue.trim().replace(/\s*!important$/, ""))) continue;
    violations.push({ file, line: lineOf(src, m.index ?? 0), msg: `${prop}: is banned (only border:0)` });
  }
}

function lintCss(src, file, violations) {
  const clean = stripComments(src, ".css");
  for (const rule of STYLE_RULES) {
    for (const m of clean.matchAll(new RegExp(rule.re.source, "g"))) {
      violations.push({ file, line: lineOf(clean, m.index ?? 0), msg: rule.msg });
    }
  }
  checkBorder(clean, file, violations);
  for (const block of clean.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const [, selector = "", body = ""] = block;
    const decl = OUTLINE_DECL.exec(body);
    if (decl && !/:focus/.test(selector)) {
      const idx = (block.index ?? 0) + block[0].indexOf(body) + decl.index;
      violations.push({ file, line: lineOf(clean, idx), msg: "outline: is banned except on a focus ring (:focus, :focus-visible)" });
    }
  }
}

function lintCode(src, file, violations) {
  const clean = stripComments(src, path.extname(file));
  for (const rule of STYLE_RULES) {
    for (const m of clean.matchAll(new RegExp(rule.re.source, "g"))) {
      violations.push({ file, line: lineOf(clean, m.index ?? 0), msg: rule.msg });
    }
  }
  checkBorder(clean, file, violations);
  // camelCase style props in objects: borderTop: "1px solid ...", outline: ...
  for (const m of clean.matchAll(/\b(border(?:Top|Right|Bottom|Left|Width|Style|Color|Inline|Block)?)\s*:\s*([^,}\n]*)/g)) {
    if (/^\s*["'`]?0(?:px)?["'`]?\s*$/.test(m[2] ?? "") && m[1] === "border") continue;
    violations.push({ file, line: lineOf(clean, m.index ?? 0), msg: `style prop ${m[1]} is banned (only border:0)` });
  }
  for (const m of clean.matchAll(/\boutline(?:Offset|Width|Style|Color)?\s*:/g)) {
    if (/focus/i.test(clean.slice(Math.max(0, (m.index ?? 0) - 200), m.index))) continue;
    violations.push({ file, line: lineOf(clean, m.index ?? 0), msg: "outline is banned except on a focus ring" });
  }
  for (const lit of PACK_LITERALS) {
    for (const m of clean.matchAll(new RegExp(lit.re.source, "g"))) {
      violations.push({
        file,
        line: lineOf(clean, m.index ?? 0),
        msg: `literal "${lit.name}" is banned in component code (read it from the country pack)`,
      });
    }
  }
}

export function lintSource(src, file) {
  const violations = [];
  const ext = path.extname(file);
  for (const phrase of BANNED_PHRASES) {
    let i = src.indexOf(phrase);
    while (i !== -1) {
      violations.push({ file, line: lineOf(src, i), msg: `copy "${phrase}" is banned` });
      i = src.indexOf(phrase, i + 1);
    }
  }
  if (CSS_EXT.has(ext)) lintCss(src, file, violations);
  else if (CODE_EXT.has(ext)) lintCode(src, file, violations);
  return violations;
}

export function lintFiles(files) {
  const violations = [];
  for (const file of files) {
    const ext = path.extname(file);
    if (!CSS_EXT.has(ext) && !CODE_EXT.has(ext) && ![".html", ".webmanifest", ".json", ".md"].includes(ext)) continue;
    violations.push(...lintSource(readFileSync(file, "utf8"), file));
  }
  return violations;
}

function main() {
  const args = process.argv.slice(2);
  const targets = (args.length ? args : DEFAULT_TARGETS).map((t) => path.resolve(root, t));
  const files = [];
  for (const t of targets) walk(t, files);
  const violations = lintFiles(files);
  for (const v of violations) {
    console.error(`${path.relative(root, v.file)}:${v.line}  ${v.msg}`);
  }
  if (violations.length) {
    console.error(`design-lint: ${violations.length} violation(s) in ${files.length} file(s)`);
    process.exit(1);
  }
  console.log(`design-lint: ok (${files.length} files)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
